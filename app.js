/* live prices from config.js (shared with admin.html + detail.html) */
function cfgPrices(){ return (window.UTOPIA_CFG && UTOPIA_CFG.prices) || {}; }
function money(n){ return "$"+(+n).toFixed(2); }
function priceWmin(){
  var P = cfgPrices(), r = +(P["drop.lb"] || 1.1);
  if(!(r > 0)) r = 1.1;
  return Math.max(1, Math.floor((+P["drop.min"] || 12) / r));
}
function fillPriceTokens(s){
  if(typeof s !== "string" || !window.UTOPIA_CFG) return s;
  var P = cfgPrices();
  return s.split("$1.10").join(money(P["drop.lb"]))
    .split("$12.00").join(money(P["drop.min"]))
    .split("$4.50").join(money(P["dry.from"]))
    .split("(10 lbs)").join("("+priceWmin()+" lbs)")
    .split("（10磅）").join("（"+priceWmin()+"磅）");
}
function applyPrices(){
  if(!window.UTOPIA_CFG) return;
  document.querySelectorAll("[data-price]").forEach(function(el){
    var v = UTOPIA_CFG.getPrice(el.dataset.price);
    if(v == null) return;
    var d = parseInt(el.dataset.fmt || "2", 10);
    el.textContent = "$" + v.toFixed(isNaN(d) ? 2 : d);
  });
}
function setLang(l){
  lang = I18N[l] ? l : "en";
  localStorage.setItem("utopia-lang", lang);
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const k = el.getAttribute("data-i18n");
    if(I18N[lang][k] !== undefined) el.innerHTML = fillPriceTokens(I18N[lang][k]);
  });
  document.querySelectorAll(".lang button").forEach(b=>b.classList.toggle("active", b.dataset.lang===lang));
  document.documentElement.lang = lang==="zh" ? "zh-CN" : lang;
  buildWeightTable();
  applyPrices();
  paintShopPrices();
  if(window.splitScrub) splitScrub();
  if(window.syncPhase) syncPhase();
  if(window.tourLabel) tourLabel();
}
document.querySelectorAll(".lang button").forEach(b=>b.addEventListener("click",()=>setLang(b.dataset.lang)));

