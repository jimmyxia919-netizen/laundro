/* reveal choreography + counters */
function animateCount(el){
  const target = parseInt(el.dataset.n,10)||0;
  const t0 = performance.now(), dur = 1200;
  (function tick(t){
    const p = Math.min(1,(t-t0)/dur), e = 1-Math.pow(1-p,3);
    el.textContent = Math.round(target*e);
    if(p<1) requestAnimationFrame(tick);
  })(t0);
}
const io = new IntersectionObserver(es=>es.forEach(e=>{
  if(!e.isIntersecting) return;
  e.target.classList.add("in");
  e.target.querySelectorAll(".count").forEach(animateCount);
  if(e.target.classList.contains("count")) animateCount(e.target);
  io.unobserve(e.target);
}),{threshold:.15});
document.querySelectorAll(".rv,.img-zoom").forEach(el=>io.observe(el));

