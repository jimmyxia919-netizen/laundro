/* language: stored > browser > en */
let lang = localStorage.getItem("utopia-lang");
if(!lang){
  const b = (navigator.language||"en").toLowerCase();
  lang = b.startsWith("zh") ? "zh" : b.startsWith("es") ? "es" : "en";
}
function setLang(l){
  lang = I18N[l] ? l : "en";
  localStorage.setItem("utopia-lang", lang);
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const k = el.getAttribute("data-i18n");
    if(I18N[lang][k] !== undefined) el.innerHTML = I18N[lang][k];
  });
  document.querySelectorAll(".lang button").forEach(b=>b.classList.toggle("active", b.dataset.lang===lang));
  document.documentElement.lang = lang==="zh" ? "zh-CN" : lang;
  buildWeightTable();
}
document.querySelectorAll(".lang button").forEach(b=>b.addEventListener("click",()=>setLang(b.dataset.lang)));

